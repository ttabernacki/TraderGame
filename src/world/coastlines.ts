/**
 * Simplified real-world coastlines for the Portuguese discovery arc.
 *
 * Each landmass is a closed ring of [lat, lon] pairs in degrees, wound so the
 * interior is land. Fidelity is roughly one vertex per 30-80 nautical miles of
 * coast, which is enough for recognisable headlands, bays and river mouths
 * without carrying a full shapefile.
 */

export interface Landmass {
  id: string;
  name: string;
  /** Flattened [lat, lon, lat, lon, ...] for compactness. */
  ring: number[];
  /** Peak elevation in metres, used to scale rendered relief. */
  relief: number;
}

