function ringFromIsle(spec: IsleSpec): number[] {
  const ring: number[] = [];
  const steps = 20;
  const rot = (spec.rot ?? 0) * (Math.PI / 180);
  const cosLat = Math.max(Math.cos(spec.lat * (Math.PI / 180)), 1e-6);
  for (let i = 0; i < steps; i++) {
    const th = (i / steps) * Math.PI * 2;
    // Slight per-vertex jitter keeps islands from reading as perfect ellipses.
    const wobble = 1 + 0.12 * Math.sin(th * 3 + spec.lat) + 0.07 * Math.cos(th * 5 - spec.lon);
    const x = Math.cos(th) * spec.b * wobble;
    const y = Math.sin(th) * spec.a * wobble;
    const xr = x * Math.cos(rot) - y * Math.sin(rot);
    const yr = x * Math.sin(rot) + y * Math.cos(rot);
    ring.push(spec.lat + yr / 60, spec.lon + xr / 60 / cosLat);
  }
  return ring;
}

